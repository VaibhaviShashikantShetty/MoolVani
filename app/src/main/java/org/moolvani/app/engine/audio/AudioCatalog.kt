    fun findSanthaliAsset(text: String): String? {
        val trimmed = text.trim()
        santhaliAssetMap[trimmed]?.let { return it }
        santhaliAssetMap[trimmed.lowercase()]?.let { return it }

        // Strip numbers like "1 - Mid" or "1 - ᱢᱤᱫ"
        val cleanNumber = trimmed.replace(Regex("^[᱐-᱙0-9]+\\s*-\\s*"), "").trim()
        santhaliAssetMap[cleanNumber]?.let { return it }
        santhaliAssetMap[cleanNumber.lowercase()]?.let { return it }

        // Strip punctuation
        val cleanPunct = trimmed.replace(Regex("[?!.,\\-_]"), "").trim()
        santhaliAssetMap[cleanPunct]?.let { return it }
        santhaliAssetMap[cleanPunct.lowercase()]?.let { return it }

        return null
    }

    fun findHindiAsset(text: String): String? {
        val trimmed = text.trim()
        hindiAssetMap[trimmed]?.let { return it }
        val cleanPunct = trimmed.replace(Regex("[?!.,\\-_]"), "").trim()
        hindiAssetMap[cleanPunct]?.let { return it }
        return null
    }
